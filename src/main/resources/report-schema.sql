-- Additive only: never reset or modify existing Workhub data.
CREATE TABLE IF NOT EXISTS financial_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_code VARCHAR(60) NOT NULL, title VARCHAR(120) NOT NULL,
 period_start DATE NOT NULL, period_end DATE NOT NULL, business_unit VARCHAR(100) NOT NULL,
 currency VARCHAR(3) NOT NULL CHECK(currency IN ('KRW','USD','EUR')),
 owner_id BIGINT NOT NULL REFERENCES users(id), reviewer_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PENDING','APPROVED','REJECTED')),
 deleted BOOLEAN NOT NULL DEFAULT FALSE, version INT NOT NULL DEFAULT 0,
 summary_note VARCHAR(2000) NOT NULL, source_id BIGINT REFERENCES financial_reports(id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(owner_id<>reviewer_id), CHECK(period_end>=period_start));
CREATE TABLE IF NOT EXISTS report_lines (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, report_id BIGINT NOT NULL REFERENCES financial_reports(id),
 line_order INT NOT NULL, label VARCHAR(120) NOT NULL, category VARCHAR(40) NOT NULL,
 amount_a DECIMAL(18,4) NOT NULL, amount_b DECIMAL(18,4) NOT NULL, amount_c DECIMAL(18,4) NOT NULL,
 memo VARCHAR(300) NOT NULL, UNIQUE(report_id,line_order));
CREATE TABLE IF NOT EXISTS report_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, report_id BIGINT NOT NULL REFERENCES financial_reports(id),
 actor VARCHAR(40) NOT NULL, action VARCHAR(30) NOT NULL, note VARCHAR(1000) NOT NULL,
 report_version INT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_reports_lookup ON financial_reports(report_code,deleted,owner_id,reviewer_id);
CREATE INDEX IF NOT EXISTS idx_report_events ON report_events(report_id,id);
